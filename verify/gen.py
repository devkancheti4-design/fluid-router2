"""GENERATE verify/verify.c FROM law/law.json AND traces/traces.json.

The C file is generated, never hand-transcribed. Copying six expressions and
sixteen traces by hand into another language is exactly the kind of step that
produces a law that verifies against the wrong thing.
"""
import os, json

HERE = os.path.dirname(os.path.abspath(__file__))
LAW = json.load(open(os.path.join(HERE, '..', 'law', 'law.json')))
TR = json.load(open(os.path.join(HERE, '..', 'traces', 'traces.json')))

lanes, names, bits = LAW['lanes'], LAW['names'], LAW['bits']
STEP = {n: i for i, n in enumerate(names)}

L = []
L.append('/* GENERATED by verify/gen.py from law/law.json and traces/traces.json.')
L.append(' * Do not edit. No dependencies: cc -O2 -o checklaws verify/verify.c')
L.append(' *')
L.append(' * Re-checks, from scratch:')
L.append(' *   1  the dispatch, on all 256 observation states, against the priority spec')
L.append(' *   2  every recorded step of all %d held-out jobs' % len(TR))
L.append(' *   3  the cost of one decision')
L.append(' */')
L.append('#include <stdio.h>')
L.append('#include <stdint.h>')
L.append('#include <time.h>')
L.append('')
L.append('/* ---- the six lanes, authored by the engine ---- */')
for i, (e, n) in enumerate(zip(lanes, names)):
    L.append('static inline int32_t LANE%d(int32_t x) { return %s; }  /* %s, bit %d */'
             % (i, e, n, bits[i]))
L.append('')
L.append('/* ---- authored for "which token do I write next", unchanged since ---- */')
L.append('static inline int32_t EMIT(int32_t m)    { return %s; }' % LAW['emit'].replace('x', 'm'))
L.append('static inline int32_t ADVANCE(int32_t m) { return %s; }' % LAW['advance'].replace('x', 'm'))
L.append('static inline int32_t HALT(int32_t m)    { return %s; }' % LAW['halt'].replace('x', 'm'))
L.append('')
L.append('static inline int32_t MASK(int32_t s)')
L.append('{')
L.append('    return ' + ' + '.join('LANE%d(s)' % i for i in range(len(lanes))) + ';')
L.append('}')
L.append('')
L.append('#define NONE (-1)')
L.append('static inline int DISPATCH(int32_t s)')
L.append('{')
L.append('    int32_t m = MASK(s);')
L.append('    if (HALT(m)) return NONE;')
L.append('    int32_t low = EMIT(m); int i = 0;')
L.append('    while (low >>= 1) i++;')
L.append('    return i;')
L.append('}')
L.append('')
L.append('static const char *NAME[%d] = {%s};'
         % (len(names), ', '.join('"%s"' % n for n in names)))
L.append('static const int BIT[%d] = {%s};' % (len(bits), ', '.join(str(b) for b in bits)))
L.append('')
L.append('/* ---- the recorded observation traces of the %d held-out jobs ---- */' % len(TR))
L.append('struct trace { const char *job; const char *truth; int n;')
L.append('               int32_t sig[8]; int step[8]; const char *outcome; };')
L.append('static const struct trace TR[%d] = {' % len(TR))
for r in TR:
    sigs = r['sigs']; steps = [STEP[s] for s in r['steps']]
    while len(steps) < len(sigs): steps.append(-1)
    steps = steps[:len(sigs)]
    L.append('  {"%s", "%s", %d, {%s}, {%s}, "%s"},'
             % (r['job'], r['truth'], len(sigs),
                ', '.join(str(s) for s in sigs),
                ', '.join(str(s) for s in steps), r['outcome']))
L.append('};')
L.append('')
L.append('int main(void)')
L.append('{')
L.append('    long wrong = 0, states = 0;')
L.append('')
L.append('    /* 1. the dispatch against the priority spec, exhaustively */')
L.append('    for (int32_t s = 0; s < 256; s++) {')
L.append('        int want = NONE;')
L.append('        for (int i = 0; i < %d; i++)' % len(bits))
L.append('            if ((s >> BIT[i]) & 1) { want = i; break; }')
L.append('        if (DISPATCH(s) != want) wrong++;')
L.append('        states++;')
L.append('    }')
L.append('    printf("  dispatch      %6ld states   %ld wrong\\n", states, wrong);')
L.append('')
L.append('    /* 2. every recorded step of every held-out job */')
L.append('    long steps = 0, bad = 0;')
L.append('    for (int t = 0; t < %d; t++) {' % len(TR))
L.append('        for (int k = 0; k < TR[t].n; k++) {')
L.append('            if (DISPATCH(TR[t].sig[k]) != TR[t].step[k]) {')
L.append('                bad++;')
L.append('                printf("  MISMATCH %s step %d sig %d\\n", TR[t].job, k, TR[t].sig[k]);')
L.append('            }')
L.append('            steps++;')
L.append('        }')
L.append('    }')
L.append('    printf("  replay        %6ld steps    %ld wrong   across %d held-out jobs\\n",')
L.append('           steps, bad, %d);' % len(TR))
L.append('')
L.append('    /* 3. ADVANCE must strictly reduce a live mask, so the loop terminates */')
L.append('    long stuck = 0;')
L.append('    for (int32_t s = 0; s < 256; s++) {')
L.append('        int32_t m = MASK(s);')
L.append('        if (!HALT(m) && !(ADVANCE(m) < m)) stuck++;')
L.append('    }')
L.append('    printf("  termination   %6d states   %ld that ADVANCE fails to reduce\\n", 256, stuck);')
L.append('')
L.append('    /* 4. what one decision costs */')
L.append('    volatile int sink = 0;')
L.append('    struct timespec a, b;')
L.append('    clock_gettime(CLOCK_MONOTONIC, &a);')
L.append('    for (long r = 0; r < 4000000L; r++)')
L.append('        for (int32_t s = 0; s < 256; s++) sink += DISPATCH(s);')
L.append('    clock_gettime(CLOCK_MONOTONIC, &b);')
L.append('    double ns = ((b.tv_sec - a.tv_sec) * 1e9 + (b.tv_nsec - a.tv_nsec))')
L.append('                / (4000000.0 * 256.0);')
L.append('    printf("  %.2f ns per decision  (sink %d)\\n", ns, sink);')
L.append('')
L.append('    printf("\\n  TOTAL  %ld dispatch states + %ld replayed steps  %ld wrong\\n",')
L.append('           states, steps, wrong + bad + stuck);')
L.append('    return (wrong + bad + stuck) != 0;')
L.append('}')

open(os.path.join(HERE, 'verify.c'), 'w').write('\n'.join(L) + '\n')
print('wrote verify/verify.c   %d lanes, %d traces' % (len(lanes), len(TR)))
